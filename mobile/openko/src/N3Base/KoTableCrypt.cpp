bool KoTableHeaderLooksValid(const uint8_t* pData, size_t nSize)
{
	if (pData == nullptr || nSize < 12)
		return false;
	uint32_t nCols = 0;
	memcpy(&nCols, pData, 4);
	if (nCols == 0 || nCols > 4096 || nSize < 4 + 4 * (size_t) nCols + 4)
		return false;
	for (uint32_t i = 0; i < nCols; i++)
	{
		uint32_t t = 0;
		memcpy(&t, pData + 4 + 4 * i, 4);
		if (t < 1 || t > 10) // DT_CHAR .. DT_DOUBLE, 10 = DT_INT64 (2xxx)
			return false;
		if (i == 0 && t != 6) // DT_DWORD
			return false;
	}
	return true;
}

bool KoTableIsLayer2(const uint8_t* pData, size_t nSize)
{
	return pData != nullptr && nSize >= 20 && (nSize % 8) == 4 && memcmp(pData, LAYER2_HEADER, 16) == 0;
}

void KoTableXorDecrypt(uint8_t* pData, size_t nSize, uint16_t key_r, uint16_t c1, uint16_t c2)
{
	for (size_t i = 0; i < nSize; i++)
	{
		uint8_t byData = (uint8_t) (pData[i] ^ (key_r >> 8));
		key_r          = (uint16_t) ((pData[i] + key_r) * c1 + c2);
		pData[i]       = byData;
	}
}

bool KoTableLayer2DecryptRaw(std::vector<uint8_t>& data)
{
	if (!KoTableIsLayer2(data.data(), data.size()))
		return false;
	uint32_t length = ((uint32_t) data[16] << 24) | ((uint32_t) data[17] << 16) | ((uint32_t) data[18] << 8) | data[19];
	std::vector<uint8_t> out(data.begin() + 20, data.end());
	if (length > out.size())
		return false;
	for (size_t i = 0; i + 8 <= out.size(); i += 8)
		DesBlock(out.data() + i);
	out.resize(length);
	KoTableXorDecrypt(out.data(), out.size(), 0x0418, 0x8041, 0x1804);
	data.swap(out);
	return true;
}

bool KoTableLayer2DecryptDesOnly(std::vector<uint8_t>& data)
{
	if (!KoTableIsLayer2(data.data(), data.size()))
		return false;
	uint32_t length = ((uint32_t) data[16] << 24) | ((uint32_t) data[17] << 16) | ((uint32_t) data[18] << 8) | data[19];
	std::vector<uint8_t> out(data.begin() + 20, data.end());
	if (length > out.size())
		return false;
	for (size_t i = 0; i + 8 <= out.size(); i += 8)
		DesBlock(out.data() + i);
	out.resize(length);
	data.swap(out);
	return true;
}

bool KoTableLayer2Decrypt(std::vector<uint8_t>& data, uint8_t* pPrefix, size_t* pPrefixLen)
{
	std::vector<uint8_t> out = data;
	if (!KoTableLayer2DecryptRaw(out))
		return false;
	// Önek genelde 5 bayt; bazı tablolarda farklı (UIs_us vb.): geçerli başlığı 0..64 ofset arasında ara
	size_t prefix = KoTableFindHeaderOffset(out.data(), out.size(), LAYER2_PREFIX);
	if (prefix == (size_t) -1)
		return false;
	if (pPrefix)
		memcpy(pPrefix, out.data(), std::min<size_t>(LAYER2_PREFIX, out.size()));
	if (pPrefixLen)
		*pPrefixLen = prefix;
	out.erase(out.begin(), out.begin() + prefix);
	data.swap(out);
	return true;
}

size_t KoTableFindHeaderOffset(const uint8_t* pData, size_t nSize, size_t nPreferred)
{
	if (pData == nullptr)
		return (size_t) -1;
	if (nPreferred < nSize && KoTableHeaderLooksValid(pData + nPreferred, nSize - nPreferred))
		return nPreferred;
	for (size_t off = 0; off <= 64 && off < nSize; off++)
		if (off != nPreferred && KoTableHeaderLooksValid(pData + off, nSize - off))
			return off;
	return (size_t) -1;
}
