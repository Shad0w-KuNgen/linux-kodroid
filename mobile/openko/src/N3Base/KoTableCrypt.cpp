const uint8_t LAYER2_HEADER[16] = { 0x4c, 0x26, 0x43, 0x7f, 0x80, 0xf1, 0x57, 0x98, 0x79, 0xfc, 0xaf, 0x26, 0x86, 0xd6,
	0x20, 0x8e };
constexpr size_t LAYER2_PREFIX = 5; // çözülen veri: [uint32 ?][uint8 sütun sayısı] + standart tablo

inline int SubkeyBit(int p)
{
	return (SUBKEYS[p >> 4] >> (p & 15)) & 1;
}

// bits: 64 × 0/1 (L = 0..31, R = 32..63); tur anahtarı rnd, son turda yer değiştirme yok
void Round(uint8_t* bits, int rnd, bool last)
{
	uint8_t ex[48];
	for (int i = 0; i < 48; i++)
		ex[i] = (uint8_t) (SubkeyBit(48 * rnd + i) ^ bits[E_TABLE[i] + 31]);
	uint8_t f[32];
	for (int k = 0; k < 8; k++)
	{
		const uint8_t* b = ex + 6 * k;
		int idx          = b[4] | 2 * (b[3] | 2 * (b[2] | 2 * (b[1] | 2 * (b[5] | 2 * b[0]))));
		uint32_t v       = S_BOX[k][idx];
		f[4 * k + 0]     = (uint8_t) ((v >> 0) & 1);
		f[4 * k + 1]     = (uint8_t) ((v >> 8) & 1);
		f[4 * k + 2]     = (uint8_t) ((v >> 16) & 1);
		f[4 * k + 3]     = (uint8_t) ((v >> 24) & 1);
	}
	if (last)
	{
		for (int i = 0; i < 32; i++)
			bits[i] ^= f[P_TABLE[i] - 1];
	}
	else
	{
		for (int i = 0; i < 32; i++)
		{
			uint8_t r    = bits[i + 32];
			bits[i + 32] = (uint8_t) (bits[i] ^ f[P_TABLE[i] - 1]);
			bits[i]      = r;
		}
	}
}

void DesBlock(uint8_t* block)
{
	uint8_t bits[64];
	for (int i = 0; i < 8; i++)
		for (int s = 0; s < 8; s++)
			bits[8 * i + s] = (uint8_t) ((block[i] >> (7 - s)) & 1);
	for (int rnd = 15; rnd >= 0; rnd--)
		Round(bits, rnd, rnd == 0);
	for (int i = 0; i < 8; i++)
	{
		uint8_t v = 0;
		for (int s = 0; s < 8; s++)
			v = (uint8_t) ((v << 1) | bits[8 * i + s]);
		block[i] = v;
	}
}
