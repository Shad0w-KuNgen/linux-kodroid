# S kutusu: 6 bitlik indeks → 4 bit (uint32'nin LE baytları = çıkış bitleri)
S = [[((v >> 0) & 1, (v >> 8) & 1, (v >> 16) & 1, (v >> 24) & 1) for v in box] for box in S_RAW]

HEADER = bytes.fromhex('4c26437f80f1579879fcaf2686d6208e')  # ham dosyanın ilk 16 baytı (sabit)
INNER_XOR = (0x0418, 0x8041, 0x1804)


def _subkey_bit(p):
    return (SUBKEYS[p >> 4] >> (p & 15)) & 1


def _round(bits, rnd, last):
    """bits: 64 x 0/1 (L=0..31, R=32..63). Tur anahtarı rnd (15..0)."""
    ex = [_subkey_bit(48 * rnd + i) ^ bits[E[i] + 31] for i in range(48)]
    f = []
    for k in range(8):
        b = ex[6 * k:6 * k + 6]
        idx = b[4] | 2 * (b[3] | 2 * (b[2] | 2 * (b[1] | 2 * (b[5] | 2 * b[0]))))
        f.extend(S[k][idx])
    if last:
        for i in range(32):
            bits[i] ^= f[P[i] - 1]
    else:
        for i in range(32):
            r = bits[i + 32]
            bits[i + 32] = bits[i] ^ f[P[i] - 1]
            bits[i] = r


def des_block(block8):
    bits = []
    for byte in block8:
        bits.extend(((byte >> s) & 1) for s in range(7, -1, -1))
    for rnd in range(15, -1, -1):
        _round(bits, rnd, rnd == 0)
    out = bytearray(8)
    for i in range(8):
        v = 0
        for j in range(8):
            v = (v << 1) | bits[8 * i + j]
        out[i] = v
    return bytes(out)


def xor_stream(data, key_r, c1, c2):
    out = bytearray(len(data))
    for i, b in enumerate(data):
        out[i] = b ^ (key_r >> 8)
        key_r = ((b + key_r) * c1 + c2) & 0xFFFF
    return bytes(out)


def is_layer2(data):
    return len(data) >= 20 and data[:16] == HEADER and len(data) % 8 == 4


def decrypt(data, inner_xor=INNER_XOR):
    """Ham .tbl → düz N3 tablo baytları. Başlık uymazsa None."""
    if not is_layer2(data):
        return None
    length = struct.unpack('>I', data[16:20])[0]
    body = data[20:]
    out = bytearray()
    for i in range(0, len(body) - len(body) % 8, 8):
        out += des_block(body[i:i + 8])
    out = bytes(out[:length])
    if inner_xor:
        out = xor_stream(out, *inner_xor)
    return out
